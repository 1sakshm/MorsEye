"""SYNTHETIC session generator, for exercising the pipeline before real data exist.

Everything it writes is marked as synthetic (header ``app_version: "synthetic"``, a SYNTHETIC note in
``setup.notes``, labeller ``SYNTHETIC``), and ``analysis.run`` marks every output made from it with
``synthetic: true``. None of it is participant data, and none of it may be reported as a result.

The distributions are plausible, not measured: spontaneous blinks log-normal (median ~180 ms,
mostly 100-400 ms) at ~10-22 per minute, deliberate short ~250-600 ms, long ~700-1400 ms, per-person
EAR/blendshape levels, some low-contrast "glasses-like" people, 15-30 fps, a few face losses.

    python -m analysis.synth OUT_DIR [--n 10] [--seed 1]
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

import numpy as np

from .replay import DEFAULT_TIMING, REVERSE_MORSE

SYNTH_NOTE = "SYNTHETIC: generated by analysis/synth.py; not participant data"

# The Study B phrase list from src/study/protocol.ts (PHRASES).
PHRASES = [
    "my watch fell in the water",
    "time to go shopping",
    "breathing is difficult",
    "the world is a stage",
    "love means many things",
    "we are having spaghetti",
    "my bank account is overdrawn",
    "a problem with the engine",
    "elephants are afraid of mice",
    "one heck of a question",
    "you must be getting old",
    "physics and chemistry are hard",
    "prevailing wind from the east",
    "never too rich and never too thin",
    "elections bring out the best",
]


@dataclass
class Person:
    pid: str
    seed: int
    fps: float
    glasses: bool
    ear_open: tuple[float, float]  # left, right
    ear_closed: tuple[float, float]
    b_open: float
    b_closed: float
    ear_noise: float
    b_noise: float
    short_med: float
    long_med: float
    good_winker: bool
    rates: dict[str, float]  # spontaneous blinks per minute by block
    age_range: str


@dataclass
class Event:
    kind: str  # spontaneous | short | long | wink-L | wink-R
    t0: float  # lids start closing
    cd: float  # closing phase, ms
    plateau: float
    rd: float  # reopening phase, ms
    depth_l: float
    depth_r: float
    onset: float  # labelled onset / offset (half-closure crossings + labeller noise)
    offset: float

    @property
    def end(self) -> float:
        return self.t0 + self.cd + self.plateau + self.rd


def _person(i: int, seed: int) -> Person:
    rng = np.random.default_rng([seed, i, 0])
    glasses = bool(rng.random() < 0.3)
    if glasses:
        eo, ec = rng.normal(0.235, 0.012), rng.normal(0.15, 0.012)
        bo, bc = rng.normal(0.13, 0.03), rng.normal(0.72, 0.06)
    else:
        eo, ec = rng.normal(0.29, 0.022), rng.normal(0.09, 0.015)
        bo, bc = rng.normal(0.06, 0.02), rng.normal(0.86, 0.05)
    asym = rng.normal(0, 0.006, size=2)
    return Person(
        pid=f"P{i + 1:02d}",
        seed=int(rng.integers(1, 2**31 - 1)),
        fps=float(rng.uniform(15, 30)),
        glasses=glasses,
        ear_open=(float(eo + asym[0]), float(eo - asym[0])),
        ear_closed=(float(ec + asym[1]), float(ec - asym[1])),
        b_open=float(np.clip(bo, 0.01, 0.3)),
        b_closed=float(np.clip(bc, 0.5, 0.98)),
        ear_noise=0.008 + (0.006 if glasses else 0.0),
        b_noise=0.03 + (0.02 if glasses else 0.0),
        short_med=float(rng.uniform(320, 480)),
        long_med=float(rng.uniform(850, 1150)),
        good_winker=bool(rng.random() < 0.75),
        rates={
            "calibration": 10.0,
            "spontaneous": float(rng.uniform(12, 22)),
            "deliberate": 9.0,
            "mixed": float(rng.uniform(10, 18)),
            "pause": 15.0,
        },
        age_range=str(rng.choice(["18-24", "18-24", "25-34", "35-44"])),
    )


def _event(kind: str, t0: float, dur: float, p: Person, rng: np.random.Generator) -> Event:
    """An eye closure whose half-closure-to-half-reopening duration is ``dur`` ms."""
    deliberate = kind != "spontaneous"
    cd = rng.uniform(80, 120) if deliberate else rng.uniform(60, 100)
    rd = rng.uniform(120, 200) if deliberate else rng.uniform(100, 180)
    plateau = dur - cd / 2 - rd / 2
    if plateau < 0:  # very short blink: shrink the ramps
        s = dur / (cd / 2 + rd / 2)
        cd, rd, plateau = cd * s, rd * s, 0.0
    depth = 1.0 if deliberate else float(rng.uniform(0.6, 1.0))
    dl = dr = depth
    if kind in ("wink-L", "wink-R"):
        other = rng.uniform(0.0, 0.15) if p.good_winker else rng.uniform(0.35, 0.7)
        dl, dr = (1.0, other) if kind == "wink-L" else (other, 1.0)
    onset = t0 + cd / 2 + rng.normal(0, 12)
    offset = t0 + cd + plateau + rd / 2 + rng.normal(0, 12)
    if offset < onset + 20:
        offset = onset + 20
    return Event(kind, t0, cd, plateau, rd, float(dl), float(dr), float(onset), float(offset))


def _lognormal(rng: np.random.Generator, median: float, sigma: float) -> float:
    return float(median * math.exp(rng.normal(0, sigma)))


def _cues(rng: np.random.Generator, kinds: list[str], lead: float, gmin: float, gmax: float, dur: float) -> list[tuple[float, str, float]]:
    t = lead
    out = []
    for k in kinds:
        out.append((t, k, dur))
        t += rng.uniform(gmin, gmax)
    return out


def _session_a(p: Person, day: int, out_dir: Path) -> Path:
    rng = np.random.default_rng([p.seed, 1])
    lines: list[tuple[float, int, dict[str, Any]]] = []
    events: list[Event] = []
    blocks: dict[str, tuple[float, float]] = {}

    def block(name: str, start: float, end: float) -> None:
        blocks[name] = (start, end)
        lines.append((start, 0, {"type": "block", "t_ms": round(start, 2), "block": name, "phase": "start"}))
        lines.append((end, 0, {"type": "block", "t_ms": round(end, 2), "block": name, "phase": "end"}))

    def respond(name: str, start: float, cues: list[tuple[float, str, float]]) -> None:
        for idx, (at, cue, dur) in enumerate(cues):
            t = start + at
            lines.append((t, 1, {"type": "cue", "t_ms": round(t, 2), "block": name, "index": idx, "cue": cue, "duration_ms": dur}))
            if cue == "OPEN" or rng.random() < 0.02:  # 2% of cues missed
                continue
            kind = {"SHORT": "short", "LONG": "long", "WINK-L": "wink-L", "WINK-R": "wink-R"}[cue]
            if kind in ("short", "long") and rng.random() < 0.03:  # wrong length; the label says what happened
                kind = "long" if kind == "short" else "short"
            d = {
                "short": lambda: _lognormal(rng, p.short_med, 0.2),
                "long": lambda: _lognormal(rng, p.long_med, 0.15),
            }.get(kind, lambda: _lognormal(rng, 450, 0.25))()
            rt = float(np.clip(rng.normal(450, 100), 250, 900))
            ev = _event(kind, t + rt, d, p, rng)
            if events and ev.t0 < events[-1].end + 150:
                continue  # would run into the previous response: treat the cue as missed
            events.append(ev)

    base = 3000.0 + float(rng.uniform(0, 2000))
    t = base + 1500
    # Calibration: 15 s eyes open, then 10 SHORT + 10 LONG in random order.
    kinds = ["SHORT"] * 10 + ["LONG"] * 10
    rng.shuffle(kinds)
    cal = [(0.0, "OPEN", 15000.0)] + _cues(rng, kinds, 16000, 2200, 2800, 1500)
    cal_end = t + cal[-1][0] + 3000
    block("calibration", t, cal_end)
    respond("calibration", t, cal)
    t = cal_end + 6000
    block("spontaneous", t, t + 180000)
    t += 180000 + 6000
    kinds = ["SHORT", "LONG", "WINK-L", "WINK-R"] * 10
    rng.shuffle(kinds)
    dl = _cues(rng, kinds, 2000, 2000, 4000, 1500)
    d_end = t + min(180000, dl[-1][0] + 3000)
    block("deliberate", t, d_end)
    respond("deliberate", t, dl)
    t = d_end + 6000
    kinds = ["SHORT", "LONG", "WINK-L", "WINK-R"] * 6
    rng.shuffle(kinds)
    mx = [c for c in _cues(rng, kinds, 4000, 4000, 8000, 2000) if c[0] < 176000]
    block("mixed", t, t + 180000)
    respond("mixed", t, mx)
    total_end = t + 180000 + 2000

    # Spontaneous blinks everywhere (a Poisson process per stretch), kept clear of other closures.
    stretches: list[tuple[float, float, float]] = []
    prev = base
    for name in ("calibration", "spontaneous", "deliberate", "mixed"):
        b0, b1 = blocks[name]
        stretches.append((prev, b0, p.rates["pause"]))
        stretches.append((b0, b1, p.rates[name]))
        prev = b1
    stretches.append((prev, total_end, p.rates["pause"]))
    for s0, s1, rate in stretches:
        tt = s0
        while True:
            tt += rng.exponential(60000.0 / rate)
            if tt >= s1:
                break
            ev = _event("spontaneous", tt, _lognormal(rng, 180, 0.35), p, rng)
            if all(ev.end + 400 < o.t0 or ev.t0 > o.end + 400 for o in events):
                events.append(ev)
    events.sort(key=lambda e: e.t0)

    # Frames: regular clock with jitter, a few dropped frames and 1-3 face losses.
    dt = 1000.0 / p.fps
    n = int((total_end - base) / dt)
    tf = base + np.arange(n) * dt + rng.normal(0, 1.0, n)
    keep = rng.random(n) > 0.006
    for _ in range(2):  # short bursts of drops
        k = int(rng.integers(0, n - 6))
        keep[k : k + int(rng.integers(3, 6))] = False
    tf = np.round(np.sort(tf[keep]), 2)
    face = np.ones(tf.size, dtype=bool)
    for _ in range(int(rng.integers(1, 4))):
        f0 = float(rng.uniform(base + 20000, total_end - 5000))
        face &= ~((tf >= f0) & (tf < f0 + float(rng.uniform(300, 1500))))

    cl = np.zeros(tf.size)
    cr = np.zeros(tf.size)
    for ev in events:
        m = (tf >= ev.t0) & (tf < ev.end)
        if not m.any():
            continue
        x = tf[m] - ev.t0
        c = np.ones(x.size)
        c = np.where(x < ev.cd, (1 - np.cos(np.pi * x / ev.cd)) / 2, c)
        r0 = ev.cd + ev.plateau
        c = np.where(x >= r0, (1 + np.cos(np.pi * np.clip(x - r0, 0, ev.rd) / ev.rd)) / 2, c)
        cl[m] = np.maximum(cl[m], ev.depth_l * c)
        cr[m] = np.maximum(cr[m], ev.depth_r * c)

    drift = 0.008 * np.sin(2 * np.pi * (tf - base) / 40000 + rng.uniform(0, 2 * np.pi))
    ear_l = p.ear_open[0] - (p.ear_open[0] - p.ear_closed[0]) * cl + drift + rng.normal(0, p.ear_noise, tf.size)
    ear_r = p.ear_open[1] - (p.ear_open[1] - p.ear_closed[1]) * cr + drift + rng.normal(0, p.ear_noise, tf.size)
    b_l = np.clip(p.b_open + (p.b_closed - p.b_open) * cl**0.8 + rng.normal(0, p.b_noise, tf.size), 0, 1)
    b_r = np.clip(p.b_open + (p.b_closed - p.b_open) * cr**0.8 + rng.normal(0, p.b_noise, tf.size), 0, 1)
    yaw = np.cumsum(rng.normal(0, 0.15, tf.size)).clip(-15, 15)
    pitch = np.cumsum(rng.normal(0, 0.1, tf.size)).clip(-10, 10)
    roll = np.cumsum(rng.normal(0, 0.08, tf.size)).clip(-8, 8)

    for k in range(tf.size):
        f = bool(face[k])
        lines.append(
            (
                float(tf[k]),
                2,
                {
                    "type": "frame",
                    "t_ms": float(tf[k]),
                    "face": f,
                    "earL": round(float(ear_l[k]), 4) if f else 0,
                    "earR": round(float(ear_r[k]), 4) if f else 0,
                    "blinkL": round(float(b_l[k]), 4) if f else 0,
                    "blinkR": round(float(b_r[k]), 4) if f else 0,
                    "yaw": round(float(yaw[k]), 2) if f else 0,
                    "pitch": round(float(pitch[k]), 2) if f else 0,
                    "roll": round(float(roll[k]), 2) if f else 0,
                    "n_faces": 1 if f else 0,
                    "eye_pts": [],
                },
            )
        )
    for t5 in np.arange(base + 5000, total_end, 5000):
        lines.append((float(t5), 3, {"type": "fps", "t_ms": round(float(t5), 2), "fps": round(p.fps + float(rng.normal(0, 0.4)), 1)}))

    started = datetime(2026, 11, 2) + timedelta(days=day, hours=10 + int(rng.integers(0, 6)))
    header = {
        "type": "header",
        "schema": "morseye-log/1",
        "app_version": "synthetic",
        "participant": p.pid,
        "session": 1,
        "study": "A",
        "seed": p.seed,
        "started_at": started.isoformat(timespec="seconds"),
        "clock": "captureTime",
        "camera_label": "synthetic camera",
        "video_width": 640,
        "video_height": 480,
        "setup": {
            "age_range": p.age_range,
            "glasses": "yes" if p.glasses else "no",
            "lighting": "synthetic",
            "camera_model": "synthetic",
            "distance_cm": "60",
            "notes": SYNTH_NOTE,
        },
        "consent": {"data": True, "video": False, "consented_at": started.isoformat(timespec="seconds")},
        "timing": DEFAULT_TIMING.to_dict(),
        "video_start_ms": None,
    }
    lines.sort(key=lambda x: (x[0], x[1]))
    path = out_dir / f"{p.pid}_A_{started.date().isoformat()}.jsonl"
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(header) + "\n")
        for _, _, d in lines:
            fh.write(json.dumps(d) + "\n")

    _write_labels(out_dir / f"{p.pid}_A_labels.csv", events, started + timedelta(days=2), rng)
    return path


def _write_labels(path: Path, events: list[Event], when: datetime, rng: np.random.Generator, relabel: bool = False) -> None:
    rows = []
    t = when
    for ev in events:
        on, off, kind = ev.onset, ev.offset, ev.kind
        if relabel:
            on += rng.normal(0, 15)
            off += rng.normal(0, 15)
            if rng.random() < 0.04:
                kind = {"short": "long", "long": "short", "spontaneous": "short"}.get(kind, kind)
            if off < on + 20:
                off = on + 20
        t += timedelta(seconds=float(rng.uniform(3, 9)))
        rows.append([f"{on:.1f}", f"{off:.1f}", kind, "SYNTHETIC", t.isoformat(timespec="seconds")])
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["onset_ms", "offset_ms", "type", "labeller", "labelled_at"])
        w.writerows(rows)


def _relabel(path_in: Path, path_out: Path, rng: np.random.Generator) -> None:
    with path_in.open(encoding="utf-8") as fh:
        r = list(csv.DictReader(fh))
    events = [
        Event(x["type"], 0, 0, 0, 0, 1, 1, float(x["onset_ms"]), float(x["offset_ms"])) for x in r
    ]
    _write_labels(path_out, events, datetime(2026, 11, 12, 15), rng, relabel=True)


def _session_b(p: Person, day: int, out_dir: Path) -> Path:
    rng = np.random.default_rng([p.seed, 2])
    order = list(PHRASES)
    rng.shuffle(order)
    blocks = [order[0:5], order[5:10], order[10:15]]
    base_cpm = float(rng.uniform(4.5, 7.5))
    base_err = float(rng.uniform(0.04, 0.10))
    letters = [c for c in REVERSE_MORSE if c.isalpha()]
    out: list[dict[str, Any]] = []
    t = 4000.0
    for bi, phrases in enumerate(blocks):
        name = f"B{bi + 1}"
        out.append({"type": "block", "t_ms": round(t, 2), "block": name, "phase": "start"})
        rate = base_cpm * (1.0, 1.18, 1.32)[bi] * math.exp(rng.normal(0, 0.08))
        err = base_err * (1.0, 0.8, 0.65)[bi]
        t += 3000
        for pi, phrase in enumerate(phrases):
            out.append({"type": "phrase", "t_ms": round(t, 2), "block": name, "index": pi, "phase": "start", "target": phrase})
            text = ""
            per_char = 60000.0 / rate

            def act(a: dict[str, Any]) -> None:
                out.append({"type": "action", "t_ms": round(t, 2), "block": name, "action": a})

            def letter(ch: str) -> None:
                nonlocal t, text
                pat = REVERSE_MORSE[ch]
                step = per_char / (len(pat) + 1)
                acc = ""
                for s in pat:
                    t += step * float(rng.uniform(0.8, 1.2))
                    acc += s
                    act({"type": "symbol", "symbol": s, "pattern": acc})
                t += step
                text += ch
                act({"type": "letter", "char": ch, "pattern": pat})

            for ch in phrase.upper():
                if ch == " ":
                    t += per_char * 1.2
                    text += " "
                    act({"type": "space"})
                    continue
                u = rng.random()
                if u < 0.02:  # unknown pattern, then the right letter
                    t += per_char * 0.8
                    act({"type": "unknown", "pattern": "......"})
                elif u < 0.05:  # partial letter cancelled with a long hold
                    t += per_char * 0.5
                    act({"type": "symbol", "symbol": "-", "pattern": "-"})
                    t += 2200
                    act({"type": "backspace", "removed": "-", "what": "pattern"})
                if rng.random() < err:
                    wrong = str(rng.choice([c for c in letters if c != ch]))
                    letter(wrong)
                    if rng.random() < 0.75:  # noticed and fixed
                        t += 2400
                        text = text[:-1]
                        act({"type": "backspace", "removed": wrong, "what": "char"})
                        letter(ch)
                else:
                    letter(ch)
            t += 1500
            out.append({"type": "phrase", "t_ms": round(t, 2), "block": name, "index": pi, "phase": "end", "target": phrase, "typed": text})
            t += 4000
        tlx = {k: float(np.clip(rng.normal(m - 6 * bi, 12), 0, 100)) for k, m in
               dict(mental=55, physical=40, temporal=45, performance=40, effort=60, frustration=35).items()}
        out.append({"type": "block", "t_ms": round(t, 2), "block": name, "phase": "end"})
        out.append({"type": "tlx", "t_ms": round(t + 500, 2), "block": name, **{k: round(v) for k, v in tlx.items()}})
        t += 30000

    started = datetime(2026, 11, 9) + timedelta(days=day, hours=11)
    header = {
        "type": "header",
        "schema": "morseye-log/1",
        "app_version": "synthetic",
        "participant": p.pid,
        "session": 2,
        "study": "B",
        "seed": p.seed,
        "started_at": started.isoformat(timespec="seconds"),
        "clock": "captureTime",
        "camera_label": "synthetic camera",
        "video_width": 640,
        "video_height": 480,
        "setup": {"age_range": p.age_range, "glasses": "yes" if p.glasses else "no", "lighting": "synthetic",
                  "camera_model": "synthetic", "distance_cm": "60", "notes": SYNTH_NOTE + " (actions only, no frames)"},
        "consent": {"data": True, "video": False, "consented_at": started.isoformat(timespec="seconds")},
        "timing": DEFAULT_TIMING.to_dict(),
        "video_start_ms": None,
    }
    path = out_dir / f"{p.pid}_B_{started.date().isoformat()}.jsonl"
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(header) + "\n")
        for d in out:
            fh.write(json.dumps(d) + "\n")
    return path


def generate(out_dir: str | Path, n: int = 10, seed: int = 1, study_b: bool = True, relabel: int = 2) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "README.txt").write_text(
        "SYNTHETIC DATA generated by analysis/synth.py. Not participant data. Never report it as results.\n",
        encoding="utf-8",
    )
    paths: list[Path] = []
    for i in range(n):
        p = _person(i, seed)
        paths.append(_session_a(p, i, out))
        if i < relabel:
            _relabel(out / f"{p.pid}_A_labels.csv", out / f"{p.pid}_A_labels_relabel.csv", np.random.default_rng([p.seed, 3]))
        if study_b:
            paths.append(_session_b(p, i, out))
    return paths


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_dir")
    ap.add_argument("--n", type=int, default=10)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--no-study-b", action="store_true")
    a = ap.parse_args(argv)
    for p in generate(a.out_dir, a.n, a.seed, not a.no_study_b):
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
