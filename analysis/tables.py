"""LaTeX tables T1-T3 and number macros for the paper (PRD §8.3).

Writes into paper/tables/:
    T1_participants.tex   participants and devices
    T2_detectors.tex      detector metrics with CIs
    T3_text_entry.tex     text-entry metrics by block
    numbers.tex           \\ME{key} macros for every reported number (use them in the prose)
    status.tex            \\synthetictrue / \\syntheticfalse

Only tabular bodies and macros are generated; captions and prose stay in main.tex.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

from . import config
from .stats import CI
from .study import StudyA, StudyB

SYNTH_COMMENT = "% SYNTHETIC DATA -- generated by analysis/synth.py. Not study results.\n"


def _esc(s: Any) -> str:
    out = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("$", r"\$")):
        out = out.replace(a, b)
    return out


def _ci(c: CI, d: int = 2, pct: bool = False) -> str:
    if not math.isfinite(c.mean):
        return "--"
    k = 100 if pct else 1
    return f"{c.mean * k:.{d}f} [{c.lo * k:.{d}f}, {c.hi * k:.{d}f}]"


def _num(x: float, d: int = 1) -> str:
    return f"{x:.{d}f}" if isinstance(x, (int, float)) and math.isfinite(x) else "--"


def t1(a: StudyA) -> str:
    rows = []
    for pa in a.participants:
        s = pa.session
        su = s.header.get("setup", {})
        n_lab = sum(pa.n_labels.values())
        rows.append(
            " & ".join(
                [
                    _esc(pa.p),
                    _esc(su.get("age_range", "")),
                    _esc(su.get("glasses", "")),
                    _esc(su.get("lighting", "")),
                    _esc(su.get("camera_model", "")),
                    _num(s.measured_fps),
                    _num(100 * s.face_frac),
                    str(n_lab),
                ]
            )
            + r" \\"
        )
    head = r"ID & Age & Glasses & Lighting & Camera & fps & Face (\%) & Labels \\"
    return "\\begin{tabular}{llllrrrr}\n\\toprule\n" + head + "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"


def t2(a: StudyA) -> str:
    rows = []
    for d, m in a.detectors.items():
        rows.append(
            " & ".join(
                [d, _esc(config.DETECTOR_LABELS[d]), _ci(m["f1"]), _ci(m["precision"]), _ci(m["recall"]), _ci(m["ftpm"], 1), _ci(m["ftpm_no_reject"], 1)]
            )
            + r" \\"
        )
    head = r"ID & Detector & F1 & Precision & Recall & FT/min & FT/min, no reject \\"
    return "\\begin{tabular}{llccccc}\n\\toprule\n" + head + "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"


def t3(b: StudyB | None) -> str:
    head = r"Block & CPM & WPM & Uncorr.\ ER (\%) & Corr.\ ER (\%) & Closures/char & Raw TLX \\"
    if b is None:
        body = r"\multicolumn{7}{c}{No Study B data yet.} \\"
    else:
        body = "\n".join(
            " & ".join(
                [
                    blk[1],
                    _ci(b.blocks[blk]["cpm"], 1),
                    _ci(b.blocks[blk]["wpm"], 2),
                    _ci(b.blocks[blk]["uncorrected"], 1, pct=True),
                    _ci(b.blocks[blk]["corrected"], 1, pct=True),
                    _ci(b.blocks[blk]["closures_per_char"], 2),
                    _ci(b.tlx[blk], 0),
                ]
            )
            + r" \\"
            for blk in ("B1", "B2", "B3")
            if blk in b.blocks
        )
    return "\\begin{tabular}{lcccccc}\n\\toprule\n" + head + "\n\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n"


def numbers(summary: dict[str, Any]) -> str:
    """\\ME{key} prints a number from summary.json. Synthetic numbers print in red with a dagger."""
    synth = summary.get("synthetic", True)
    out = [
        "% Generated by analysis/tables.py from analysis/out/summary.json. Do not edit.",
        "\\makeatletter",
        "\\newcommand{\\ME}[1]{\\@ifundefined{ME@#1}{\\textbf{??#1??}}{\\MEfmt{\\csname ME@#1\\endcsname}}}",
        "\\newcommand{\\MEfmt}[1]{\\textcolor{red}{#1\\textsuperscript{\\dag}}}" if synth else "\\newcommand{\\MEfmt}[1]{#1}",
    ]

    def put(key: str, val: str) -> None:
        out.append(f"\\expandafter\\def\\csname ME@{key}\\endcsname{{{val}}}")

    put("nA", str(summary["study_a"]["n_participants"]))
    put("nB", str(summary["study_b"]["n_participants"] if summary.get("study_b") else 0))
    put("nLabels", str(summary["study_a"].get("n_labels_total", 0)))
    for d, m in summary["study_a"].get("detectors", {}).items():
        for key in ("f1", "precision", "recall", "ftpm", "ftpm_no_reject", "dur_err_abs"):
            c = m[key]
            digits = 2 if key in ("f1", "precision", "recall") else (0 if key == "dur_err_abs" else 1)
            put(f"{key}-{d}", _fmt_ci(c, digits))
            put(f"{key}-{d}-mean", _fmt(c["mean"], digits))
    for p in summary["study_a"].get("kshot", []):
        put(f"f1-{p['detector']}-k{p['k']}", _fmt_ci(p["f1"], 2))
    if summary.get("study_b"):
        for blk, m in summary["study_b"]["blocks"].items():
            put(f"cpm-{blk}", _fmt_ci(m["cpm"], 1))
            put(f"uer-{blk}", _fmt_ci({k: (v * 100 if isinstance(v, (int, float)) else v) for k, v in m["uncorrected"].items()}, 1))
    out.append("\\makeatother")
    return "\n".join(out) + "\n"


def _fmt(x: Any, d: int) -> str:
    return f"{x:.{d}f}" if isinstance(x, (int, float)) and math.isfinite(x) else "--"


def _fmt_ci(c: dict[str, Any], d: int) -> str:
    if c is None or not isinstance(c.get("mean"), (int, float)) or not math.isfinite(c["mean"]):
        return "--"
    return f"{c['mean']:.{d}f} [{c['lo']:.{d}f}, {c['hi']:.{d}f}]"


def write_all(a: StudyA | None, b: StudyB | None, summary: dict[str, Any], out_dir: Path, synthetic: bool) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    pre = SYNTH_COMMENT if synthetic else ""
    files: dict[str, str] = {
        "status.tex": "\\newif\\ifsynthetic\n" + ("\\synthetictrue\n" if synthetic else "\\syntheticfalse\n"),
        "numbers.tex": numbers(summary),
        "T3_text_entry.tex": pre + t3(b),
    }
    if a and a.participants:
        files["T1_participants.tex"] = pre + t1(a)
        files["T2_detectors.tex"] = pre + t2(a)
    else:
        files["T1_participants.tex"] = "No Study A data yet.\n"
        files["T2_detectors.tex"] = "No Study A data yet.\n"
    paths = []
    for name, text in files.items():
        p = out_dir / name
        p.write_text(text, encoding="utf-8")
        paths.append(p)
    return paths
